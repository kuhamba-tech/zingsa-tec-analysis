class BroadcastEphemerisParserTests(unittest.TestCase):
    def test_rinex3_keeps_latest_gps_and_skips_beidou(self) -> None:
        import pandas as pd

        rows = _parse_rinex_gps_nav(_SAMPLE)
        self.assertEqual([row["sv"] for row in rows], ["G01", "G01"])
        nav = _latest_per_sv(pd.DataFrame(rows), datetime(2026, 10, 25, 1, 0, tzinfo=timezone.utc))
        self.assertEqual(set(nav), {1})
        self.assertAlmostEqual(nav[1]["sqrtA"], 5153.8, places=1)
        self.assertAlmostEqual(nav[1]["Toe"], 518400.0, places=1)

    def test_rinex2_d_exponent(self) -> None:
        rows = _parse_rinex_gps_nav(_RINEX2)
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0]["sv"], "G01")
        self.assertAlmostEqual(rows[0]["sqrtA"], 5153.741504669, places=3)


if __name__ == "__main__":
    unittest.main()
