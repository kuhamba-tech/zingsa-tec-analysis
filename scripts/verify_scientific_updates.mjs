import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "../frontend/node_modules/typescript/lib/typescript.js";
const source=await readFile(new URL("../frontend/lib/scientificUpdate.ts",import.meta.url),"utf8");
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const helper={exports:{}};
new Function("exports","module",compiled)(helper.exports,helper);
const {scientificSnapshot,scientificEvents,utcLabel}=helper.exports;
const time="2026-10-31T04:00:00Z", now=Date.parse(time);
const feed={fresh:true,timestamp:time};
const solar={flux:2e-6,flare_class:"C2.0",solar_wind:{speed:500,bz:4,bt:7,density:5,temperature:100000,southward_duration_minutes:0},feed_status:{goes_xray:feed,solar_wind_plasma:feed,solar_wind_mag:feed},donki_flares:[],donki_cmes:[]};
let rows=scientificSnapshot(solar,now);
assert.match(rows[0].text,/C2.0/);assert.match(rows[0].text,/instantaneous/);
assert.match(rows[1].text,/500 km\/s/);assert.match(rows[2].text,/Bz 4.0 nT/);
assert.match(rows[2].interpretation,/cannot determine a storm/);
rows=scientificSnapshot(solar,now+21*60000);
assert(rows.every(r=>/No fresh/.test(r.text)));
assert(scientificSnapshot(null,now).every(r=>/No fresh/.test(r.text)));
const invalid={...solar,flux:NaN};assert.match(scientificSnapshot(invalid,now)[0].text,/No fresh/);
const future={...solar,feed_status:{goes_xray:{...feed,timestamp:"2027-01-01T00:00:00Z"}}};
assert.match(scientificSnapshot(future,now)[0].text,/No fresh/);
assert.equal(utcLabel("2026-10-31 04:00:00"),"2026-10-31 04:00:00 UTC");
assert.equal(utcLabel("not a time"),"Unavailable");
const events=scientificEvents({...solar,donki_flares:[{flrID:"old",classType:"C1.0",peakTime:"2026-10-30T05:00Z"},{flrID:"future",classType:"X9.0",peakTime:"2027-01-01T00:00Z"}],donki_cmes:[{activityID:"new",startTime:"2026-10-31T03:00Z",linkedEvents:[{}],cmeAnalyses:[{speed:900,halfAngle:180}]}]},now);
assert.equal(events.length,2);assert.equal(events[0].id,"new");
assert.match(events[0].detail,/not inferred/);
assert(!JSON.stringify(events).includes("future"));
console.log("PASS: fresh/stale/missing/future/nonfinite observations, UTC timestamps, chronological events and no inferred CME impact");
